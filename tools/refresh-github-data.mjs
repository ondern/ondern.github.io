// Refreshes data/projects.json from GitHub's public REST API (no token, public data only).
// Run on your own machine: `npm run refresh:github`, review `git diff data/projects.json`, then commit.
// The website never calls GitHub when a visitor opens it; it only reads the saved file.
import { writeFileSync } from 'node:fs';

const USER = 'ondern';
const EXCLUDE_REPOS = ['ondern.github.io']; // the website's own repository is not listed
const MAX_PULLS = 8;
const headers = { 'User-Agent': 'nuray-site-refresh', Accept: 'application/vnd.github+json' };
const get = async (url) => {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
};
const today = new Date().toISOString().slice(0, 10);

const list = await get(`https://api.github.com/users/${USER}/repos?per_page=100&sort=pushed&type=owner`);
const featured = [];
for (const r of list.filter((x) => !x.private && !x.archived && !EXCLUDE_REPOS.includes(x.name.toLowerCase()))) {
  const d = await get(`https://api.github.com/repos/${USER}/${r.name}`);
  const entry = { name: d.name, fork: !!d.fork };
  if (d.fork && d.parent) entry.upstream = { fullName: d.parent.full_name, url: d.parent.html_url, language: d.parent.language || d.language || null };
  entry.snapshot = { description: d.description || '', retrieved: today, pushedAt: d.pushed_at };
  featured.push(entry);
}
featured.sort((a, b) => b.snapshot.pushedAt.localeCompare(a.snapshot.pushedAt));

const found = await get(`https://api.github.com/search/issues?q=${encodeURIComponent(`author:${USER} type:pr is:public`)}&sort=updated&order=desc&per_page=50`);
const pulls = found.items.map((i) => {
  const repo = i.repository_url.replace('https://api.github.com/repos/', '');
  const merged = !!i.pull_request?.merged_at;
  return { repo, number: i.number, title: i.title, url: i.html_url, state: i.state === 'open' ? 'open' : merged ? 'merged' : 'closed', updatedAt: i.updated_at };
}).filter((p) => p.state !== 'closed' && !EXCLUDE_REPOS.includes(p.repo.split('/')[1].toLowerCase()))
  .sort((a, b) => (a.state === b.state ? b.updatedAt.localeCompare(a.updatedAt) : a.state === 'open' ? -1 : 1))
  .slice(0, MAX_PULLS);

const out = {
  _readme: `Public data from github.com/${USER}, stored locally so the site never calls the GitHub API when a visitor opens it. Generated by tools/refresh-github-data.mjs (npm run refresh:github) on ${today}. The website repository is excluded. Pull requests are listed when open or merged; closed-without-merge ones are left out.`,
  featured,
  pulls,
};
writeFileSync('data/projects.json', JSON.stringify(out, null, 2) + '\n', 'utf8');
console.log(`repos: ${featured.map((f) => f.name).join(', ')}\npull requests: ${pulls.length} (${pulls.filter((p) => p.state === 'open').length} open)`);
